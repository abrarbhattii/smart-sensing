// Exports all content tables from Supabase into supabase/03_seed.sql
// (plain INSERT statements, parents before children).
// Usage: node scripts/export-seed-sql.mjs
// Uses SUPABASE_SERVICE_ROLE_KEY when present (includes unpublished rows),
// otherwise the public anon key (published rows only).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
try {
    process.loadEnvFile(join(root, '.env.local'));
}
catch {
    // Fall back to variables already present in the environment.
}

const url = process.env.VITE_SUPABASE_URL;
const key = (process.env.SEED_USE_ANON ? null : process.env.SUPABASE_SERVICE_ROLE_KEY) || process.env.VITE_SUPABASE_ANON_KEY;
if (!url || !key) {
    console.error('Missing VITE_SUPABASE_URL and a Supabase key in .env.local');
    process.exit(1);
}

const TABLES = [
    'recent_work', 'recent_work_tags', 'collaborators',
    'who_we_are_intro', 'who_we_are_pillars', 'who_we_are_facts',
    'key_area_pillars', 'key_area_nodes', 'key_area_node_tags', 'key_area_node_pillars',
    'team_members', 'team_bios', 'team_bio_publications', 'team_bio_chapters', 'team_bio_awards',
    'sawaid_activity', 'sawaid_projects', 'sawaid_fingerprint_keyphrases', 'sawaid_fingerprint_themes',
    'sawaid_profile', 'sawaid_interests', 'sawaid_keywords', 'sawaid_education',
    'sawaid_appointments', 'sawaid_outputs', 'sawaid_editorial_roles',
    'lab_hub_intro', 'lab_hub_entries', 'research_areas', 'research_area_tags',
    'publications', 'publication_keywords', 'projects', 'project_badges',
    'project_images', 'project_highlights',
    'apps_tools_intro', 'apps_tools', 'apps_tool_tags',
    'society_intro', 'society_event_groups', 'society_event_items', 'society_event_item_highlights',
    'society_event_item_sections',
    'events', 'event_highlights', 'event_tags',
    'academy_intro', 'academy_sections', 'academy_items', 'academy_item_points', 'academy_item_files',
    'academy_item_sections',
];
const SKIP_COLUMNS = new Set(['created_at', 'updated_at']);

function literal(value) {
    if (value === null || value === undefined)
        return 'null';
    if (typeof value === 'boolean')
        return value ? 'true' : 'false';
    if (typeof value === 'number')
        return String(value);
    return `'${String(value).replace(/'/g, "''")}'`;
}

async function fetchTable(table) {
    const res = await fetch(`${url}/rest/v1/${table}?select=*`, {
        headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (res.status === 404)
        return null;
    if (!res.ok)
        throw new Error(`${table}: ${res.status} ${await res.text()}`);
    const rows = await res.json();
    return rows.sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0));
}

const out = [
    '-- =====================================================================',
    '-- SCD content seed. Only for an EMPTY project.',
    '-- Run order: 01_schema.sql -> 02_security.sql -> 05_cards_and_apps.sql',
    '--            -> 06_detail_pages.sql -> 03_seed.sql',
    `-- Generated by scripts/export-seed-sql.mjs on ${new Date().toISOString()}`,
    '-- Values mirror the live database / site snapshot at generation time.',
    '-- =====================================================================',
    '',
    'begin;',
    '',
    'do $$',
    'begin',
    '  if exists (select 1 from public.team_members) then',
    "    raise exception 'Content already exists; 03_seed.sql is only for an empty project.';",
    '  end if;',
    'end $$;',
    '',
];

for (const table of TABLES) {
    const rows = await fetchTable(table);
    if (!rows || rows.length === 0)
        continue;
    const columns = Object.keys(rows[0]).filter((c) => !SKIP_COLUMNS.has(c));
    out.push(`-- ${table} (${rows.length})`);
    out.push(`insert into public.${table} (${columns.join(', ')}) values`);
    out.push(rows.map((row) => `  (${columns.map((c) => literal(row[c])).join(', ')})`).join(',\n') + ';');
    out.push('');
}

const fixes = readFileSync(join(root, 'supabase', '04_content_updates.sql'), 'utf8');
out.push('-- Content updates (same as 04_content_updates.sql; no-ops when already applied)');
out.push(fixes.replace(/^--.*\n/gm, '').trim());
out.push('');
out.push('commit;');
out.push('');

writeFileSync(join(root, 'supabase', '03_seed.sql'), out.join('\n'));
console.log('Wrote supabase/03_seed.sql');
